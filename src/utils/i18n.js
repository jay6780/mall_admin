const localizedFieldAliases = {
  zh: ['name_zh', 'nameZh', 'title_zh', 'titleZh', 'description_zh', 'descriptionZh', 'content_zh', 'contentZh', 'remark_zh', 'remarkZh', 'label_zh', 'labelZh'],
  en: ['name_en', 'nameEn', 'title_en', 'titleEn', 'description_en', 'descriptionEn', 'content_en', 'contentEn', 'remark_en', 'remarkEn', 'label_en', 'labelEn']
}

const displayFieldNames = ['name', 'title', 'description', 'content', 'remark', 'label']

function getLocalizedFieldValue(value, lang = 'zh') {
  if (!value || typeof value !== 'object') {
    return null
  }

  const aliases = localizedFieldAliases[lang] || localizedFieldAliases.zh
  for (const alias of aliases) {
    if (value[alias] !== undefined && value[alias] !== null && value[alias] !== '') {
      return value[alias]
    }
  }

  for (const field of displayFieldNames) {
    if (value[field] !== undefined && value[field] !== null && value[field] !== '') {
      return value[field]
    }
  }

  return null
}

export function applyLocalizationToData(data, lang = 'zh') {
  if (Array.isArray(data)) {
    return data.map(item => applyLocalizationToData(item, lang))
  }

  if (!data || typeof data !== 'object') {
    return data
  }

  const localizedValue = getLocalizedFieldValue(data, lang)
  if (localizedValue !== null) {
    for (const field of displayFieldNames) {
      if (data[field] !== undefined && data[field] !== null && data[field] !== '') {
        data[field] = localizedValue
        break
      }
    }
  }

  Object.keys(data).forEach(key => {
    if (data[key] && typeof data[key] === 'object') {
      data[key] = applyLocalizationToData(data[key], lang)
    }
  })

  return data
}

export function translate(key, lang = 'zh') {
  const locale = messages[lang] || messages.zh
  const parts = key.split('.')
  let value = locale

  for (const part of parts) {
    if (!value || typeof value !== 'object') {
      return key
    }
    value = value[part]
  }

  return value || key
}

export function translateTitle(title, lang = 'zh') {
  if (!title) {
    return ''
  }
  const mapped = routeTitleMap[lang] && routeTitleMap[lang][title]
  return mapped || title
}

export function getLanguageLabel(lang = 'zh') {
  return lang === 'en' ? 'English' : '中文'
}
